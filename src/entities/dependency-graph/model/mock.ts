import type {
  DependencyGraph,
  IngredientNode,
  DishNode,
  RecipeEdge,
} from "./type.ts";

const ingredient = (
  id: string,
  name: string,
  quantity: number,
  status: IngredientNode["data"]["status"] = "available",
  unit = "кг",
): IngredientNode => ({
  id,
  type: "ingredient",
  data: { name, quantity, unit, status },
});
const dish = (
  id: string,
  name: string,
  status: DishNode["data"]["status"] = "available",
): DishNode => ({ id, type: "dish", data: { name, status } });
const recipe = (
  id: string,
  source: string,
  target: string,
  required: number,
  status: RecipeEdge["data"]["status"] = "available",
  unit = "кг",
): RecipeEdge => ({ id, source, target, data: { required, unit, status } });

